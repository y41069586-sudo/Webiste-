export function getPalette(id: string): Palette {
  const p = PALETTES.find((x) => x.id === id);
  if (!p) throw new Error(`Unbekannte Palette: ${id}`);
  return p;
}

export function paletteCssVars(p: Palette): string {
  return [
    `--c-primary:${p.primary}`,
    `--c-primary-dark:${p.primaryDark}`,
    `--c-on-primary:${p.onPrimary}`,
    `--c-accent:${p.accent}`,
    `--c-on-accent:${p.onAccent}`,
    `--c-surface:${p.surface}`,
    `--c-surface-alt:${p.surfaceAlt}`,
    `--c-ink:${p.ink}`,
    `--c-muted:${p.muted}`,
    `--c-line:${p.line}`,
    `--f-heading:${p.fontHeading}`,
    `--f-body:${p.fontBody}`,
  ].join(';');
}

// --- WCAG-Kontrast -----------------------------------------------------------
function channel(c: number): number {
  const s = c / 255;
  return s <= 0.03928 ? s / 12.92 : ((s + 0.055) / 1.055) ** 2.4;
}

export function luminance(hex: string): number {
  const h = hex.replace('#', '');
  const n = parseInt(
    h.length === 3
      ? h
          .split('')
          .map((x) => x + x)
          .join('')
      : h,
    16,
  );
  return 0.2126 * channel((n >> 16) & 255) + 0.7152 * channel((n >> 8) & 255) + 0.0722 * channel(n & 255);
}

export function contrastRatio(a: string, b: string): number {
  const la = luminance(a);
  const lb = luminance(b);
  return (Math.max(la, lb) + 0.05) / (Math.min(la, lb) + 0.05);
}
